import { useEffect, useRef, useState } from 'react'
import { toast } from 'sonner'
import type { IpadPairing } from '@shared/ipad'
import { Lock, Tablet } from '@/components/icons'
import { Button } from '@/components/ui/button'
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle } from '@/components/ui/dialog'
import { Switch } from '@/components/ui/switch'
import { useIpadStatus } from './status'
import { t, tRich } from '@/lib/i18n'

/** One-time pairing: a QR code with a pairing token + key in the URL fragment. Closes once the iPad is paired. */
export function PairIpadDialog({ open, onOpenChange }: { open: boolean; onOpenChange: (open: boolean) => void }) {
  const [pairing, setPairing] = useState<IpadPairing | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [useIp, setUseIp] = useState(false)
  const [now, setNow] = useState(Date.now())
  const status = useIpadStatus()
  const known = useRef<Set<string> | null>(null)

  const load = async (): Promise<void> => {
    setError(null)
    const res = await window.ipad.pair()
    if ('error' in res) {
      setPairing(null)
      setError(res.error)
    } else setPairing(res)
  }

  useEffect(() => {
    if (!open) {
      setPairing(null)
      known.current = null
      return
    }
    known.current = new Set(status.devices.map((d) => d.id))
    void load()
    const timer = setInterval(() => setNow(Date.now()), 1000)
    return () => clearInterval(timer)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open])

  // a new device showed up: pairing done
  useEffect(() => {
    if (!open || !known.current) return
    const added = status.devices.find((d) => !known.current!.has(d.id))
    if (added) {
      toast.success(t('ipad.pairedToast', { name: added.name }), { description: t('ipad.pairedToastHint') })
      onOpenChange(false)
    }
  }, [status.devices, open, onOpenChange])

  const expired = pairing ? pairing.expiresAt <= now : false
  const left = pairing ? Math.max(0, Math.round((pairing.expiresAt - now) / 1000)) : 0

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="sm:max-w-md">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <Tablet className="size-5" /> {t('ipad.pair')}
          </DialogTitle>
          <DialogDescription>{t('ipad.pairHint')}</DialogDescription>
        </DialogHeader>
        <div className="flex flex-col items-center gap-3">
          {error && <p className="text-sm text-destructive">{error}</p>}
          {pairing && !expired && (
            <div
              className="size-60 rounded-xl border bg-white p-2 [&_svg]:size-full"
              // the SVG is generated by the qrcode library in main from our own URL
              dangerouslySetInnerHTML={{ __html: useIp ? pairing.ipQrSvg : pairing.qrSvg }}
            />
          )}
          {pairing && expired && (
            <div className="grid size-60 place-items-center rounded-xl border text-sm text-muted-foreground">
              <Button variant="outline" onClick={() => void load()}>
                {t('ipad.newQr')}
              </Button>
            </div>
          )}
          {pairing && !expired && <p className="text-xs text-muted-foreground">{t('ipad.valid', { time: `${Math.floor(left / 60)}:${String(left % 60).padStart(2, '0')}` })}</p>}
          <label className="flex items-center gap-2 text-xs text-muted-foreground">
            <Switch checked={useIp} onCheckedChange={setUseIp} /> {t('ipad.useIp')}
          </label>
          <ol className="w-full list-decimal space-y-1 pl-5 text-sm text-muted-foreground">
            <li>{t('ipad.step1')}</li>
            <li>{tRich('ipad.step2', { action: <b>{t('ipad.step2Action')}</b> })}</li>
            <li>{t('ipad.step3')}</li>
          </ol>
          <p className="flex items-center gap-1.5 self-start text-xs text-muted-foreground">
            <Lock className="size-3.5" /> {t('ipad.pairPrivacy')}
          </p>
        </div>
      </DialogContent>
    </Dialog>
  )
}
