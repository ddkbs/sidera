// Renders the macOS menu-bar template icon (black + alpha, 18pt @1x/@2x) from build/logoTemplate.svg into
// src/main/trayIcon.ts as base64. Run: npx electron scripts/make-tray-icon.cjs
const { app, BrowserWindow } = require('electron')
const { readFileSync, writeFileSync } = require('node:fs')
const { join } = require('node:path')
const { withRenderer } = require('./raster.cjs')

const svg = readFileSync(join(__dirname, '../build/logoTemplate.svg'), 'utf8')

withRenderer(app, BrowserWindow, async (render) => {
  const x1 = (await render(svg, 18)).toString('base64')
  const x2 = (await render(svg, 36)).toString('base64')
  writeFileSync(
    join(__dirname, '../src/main/trayIcon.ts'),
    `// Generated by scripts/make-tray-icon.cjs — do not edit.\nexport const TRAY_ICON_1X = '${x1}'\nexport const TRAY_ICON_2X = '${x2}'\n`
  )
})
