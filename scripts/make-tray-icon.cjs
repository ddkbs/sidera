// Renders the macOS menu-bar template icon (black + alpha, 18pt @1x/@2x) into src/main/trayIcon.ts as base64.
// Run: npx electron scripts/make-tray-icon.cjs
const { app, BrowserWindow } = require('electron')
const { writeFileSync } = require('node:fs')
const { join } = require('node:path')

// two linked cards — the app logo reduced to strokes
const svg = (s) => `<svg xmlns="http://www.w3.org/2000/svg" width="${s}" height="${s}" viewBox="0 0 18 18" fill="none" stroke="#000" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">
  <rect x="1.75" y="2.75" width="8.5" height="6" rx="1.6"/>
  <rect x="7.75" y="9.25" width="8.5" height="6" rx="1.6"/>
  <path d="M6 8.75v1.5a2 2 0 0 0 1.75 1.99"/>
  <path d="M4.25 5.25h3.5" stroke-width="1.3"/>
  <path d="M10.25 11.75h3.5" stroke-width="1.3"/>
</svg>`

async function render(win, size) {
  await win.loadURL('data:text/html;charset=utf-8,' + encodeURIComponent(`<body style="margin:0;background:transparent">${svg(size)}</body>`))
  await new Promise((r) => setTimeout(r, 200))
  const img = await win.webContents.capturePage({ x: 0, y: 0, width: size, height: size })
  return img.resize({ width: size, height: size }).toPNG().toString('base64')
}

app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 64, height: 64, show: false, transparent: true, frame: false, useContentSize: true, webPreferences: { zoomFactor: 1 } })
  win.webContents.setZoomFactor(1)
  const x1 = await render(win, 18)
  const x2 = await render(win, 36)
  writeFileSync(
    join(__dirname, '../src/main/trayIcon.ts'),
    `// Generated by scripts/make-tray-icon.cjs — do not edit.\nexport const TRAY_ICON_1X = '${x1}'\nexport const TRAY_ICON_2X = '${x2}'\n`
  )
  app.quit()
})
